#!/usr/bin/env python3
"""Generate the Homebrew formula for the Hive contributor wrapper."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
from pathlib import Path

WRAPPER_TEMPLATE = Path(__file__).with_name("contribute-wrapper.sh.in")


def ruby_quote(value: str) -> str:
    return value.replace('\\', '\\\\').replace('"', '\\"')


def class_name(formula: str) -> str:
    return ''.join(part.capitalize() for part in formula.replace('_', '-').split('-'))


def parse_generated_at(value: str) -> datetime:
    stamp = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if stamp.tzinfo is None:
        stamp = stamp.replace(tzinfo=timezone.utc)
    return stamp.astimezone(timezone.utc)


def formula_version(args: argparse.Namespace) -> str:
    """Return a version that grows on every generation.

    Homebrew upgrades a keg only when the formula version compares greater
    than the installed one, and it compares digest strings token by token
    (letters sort below digits; "a1"/"b2" even parse as alpha/beta
    pre-releases). A bare digest is therefore not orderable, and a wrapper
    fix regenerated under the same digest never reaches installed users.
    Two leading numeric tokens from the generation time make every later
    generation greater than every earlier one; the digest stays for
    traceability.
    """
    stamp = parse_generated_at(args.generated_at)
    return f"{stamp:%Y%m%d.%H%M%S}.{args.version}"


def render_wrapper(args: argparse.Namespace, sif: str, caveat_channel: str) -> str:
    values = {
        "@VERSION@": ruby_quote(formula_version(args)),
        "@CHANNEL@": ruby_quote(args.channel),
        "@IMAGE_REF@": ruby_quote(args.image_ref),
        "@DIGEST@": ruby_quote(args.digest),
        "@SIF@": sif,
        "@BINARY@": args.binary,
        "@CAVEAT_CHANNEL@": caveat_channel,
    }
    text = WRAPPER_TEMPLATE.read_text(encoding="utf-8")
    for key, value in values.items():
        text = text.replace(key, value)
    return text


def render(args: argparse.Namespace) -> str:
    klass = class_name(args.formula)
    prerelease = " (pre-release candidate channel)" if args.channel == "candidate" else ""
    caveat_channel = "candidate pre-release" if args.channel == "candidate" else "stable"
    binary = args.binary
    sif = f"hive-contributor-{args.channel}.sif"
    return f'''# typed: false
# frozen_string_literal: true

# This file is generated by scripts/generate-formula.py. Do not hand-edit.
class {klass} < Formula
  desc "Hive contribute relay wrapper{prerelease}"
  homepage "https://github.com/hivecommons/hive"
  version "{ruby_quote(formula_version(args))}"
  license "Apache-2.0"

  if Hardware::CPU.arm?
    url "{ruby_quote(args.arm64_url)}"
    sha256 "{ruby_quote(args.arm64_sha256)}"
  else
    url "{ruby_quote(args.amd64_url)}"
    sha256 "{ruby_quote(args.amd64_sha256)}"
  end

  on_linux do
    depends_on "apptainer"
  end

  def install
    libexec.install Dir["*.sif"].first => "{sif}"
    (bin/"{binary}").write <<~SH
{render_wrapper(args, sif, caveat_channel)}    SH
  end

  def caveats
    <<~EOS
      This formula tracks the {caveat_channel} channel resolved at generation time:
        {args.image_ref}

      Linux uses Apptainer natively. Homebrew's apptainer formula is Linux-only;
      on macOS the wrapper uses Docker or Podman when present, or a Lima VM when
      HIVE_CONTRIBUTE_RUNTIME=lima and an apptainer VM has been created.

      The wrapper does not claim automatic KVM/gVisor confinement for Apptainer.
      gVisor is only used when Docker/Podman is selected with
      HIVE_CONTRIBUTE_RUNTIME=gvisor and runsc is installed/configured for that
      engine; runsc/KVM platform selection is managed by gVisor, not this formula.

      Behaviour change: the wrapper no longer mounts ~/.ssh or ~/.config/gh into
      the container by default. Git inside the container uses HTTPS with the
      GH_TOKEN (or GITHUB_TOKEN) the wrapper forwards, via an env-configured git
      credential helper; without a token, authenticated clones and pushes fail
      and the wrapper prints a warning. To restore the old mounts, set
        HIVE_CONTRIBUTE_MOUNT_SSH=1   (read-only ~/.ssh)
        HIVE_CONTRIBUTE_MOUNT_GH=1    (~/.config/gh)
      ~/.gitconfig is still mounted read-only: a url.<base>.insteadOf rule that
      rewrites https://github.com/ to SSH bypasses the HTTPS helper and needs
      HIVE_CONTRIBUTE_MOUNT_SSH=1.
    EOS
  end

  test do
    assert_match(
      "{binary} {ruby_quote(formula_version(args))}",
      shell_output("#{{bin}}/{binary} --wrapper-version"),
    )
  end
end
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--formula', default='contribute')
    parser.add_argument('--binary', default='hive-contribute')
    parser.add_argument('--channel', choices=['stable', 'candidate'], default='stable')
    parser.add_argument('--version', required=True,
                        help='image digest prefix; the formula version is <YYYYMMDD>.<HHMMSS>.<this>')
    parser.add_argument('--generated-at', default=datetime.now(timezone.utc).isoformat(),
                        help='ISO-8601 generation time used for the version prefix (default: now, UTC)')
    parser.add_argument('--digest', required=True)
    parser.add_argument('--image-ref', required=True)
    parser.add_argument('--amd64-url', required=True)
    parser.add_argument('--amd64-sha256', required=True)
    parser.add_argument('--arm64-url', required=True)
    parser.add_argument('--arm64-sha256', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    try:
        parse_generated_at(args.generated_at)
    except ValueError as exc:
        parser.error(f"--generated-at: {exc}")
    Path(args.output).write_text(render(args), encoding='utf-8')


if __name__ == '__main__':
    main()
