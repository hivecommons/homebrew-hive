#!/usr/bin/env python3
"""Unit tests for scripts/generate-formula.py.

Run from the repository root:

    python3 -m unittest discover -s scripts -p 'test_*.py' -v

The tests render the formula with fixed inputs, check the Ruby output, then
extract the embedded bash wrapper and exercise it against stub container
runtimes so the hand-off of environment, binds and relay arguments is checked
without Homebrew, Apptainer or Docker being installed.
"""
from __future__ import annotations

import argparse
import importlib.util
import os
import re
import shutil
import stat
import subprocess
import sys
import tempfile
import textwrap
import unittest
from pathlib import Path

SCRIPTS_DIR = Path(__file__).resolve().parent
GENERATOR = SCRIPTS_DIR / "generate-formula.py"

# Minimal host tools the wrapper needs; everything else is kept off PATH so
# the tests never pick up a real container runtime.
HOST_TOOLS = ("bash", "uname", "tr", "mkdir", "env", "sort", "cat", "sh", "mktemp", "rm", "cp")


def load_generator():
    spec = importlib.util.spec_from_file_location("generate_formula", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


gen = load_generator()


def make_args(**overrides) -> argparse.Namespace:
    values = dict(
        formula="contribute",
        binary="hive-contribute",
        channel="stable",
        version="8d0610f72958",
        digest="sha256:" + "8d" * 32,
        image_ref="ghcr.io/hivecommons/hive-contributor@sha256:" + "8d" * 32,
        amd64_url="https://github.com/hivecommons/homebrew-hive/releases/download/contribute-8d0610f72958/hive-contributor-amd64.sif",
        amd64_sha256="a" * 64,
        arm64_url="https://github.com/hivecommons/homebrew-hive/releases/download/contribute-8d0610f72958/hive-contributor-arm64.sif",
        arm64_sha256="b" * 64,
        output="unused",
    )
    values.update(overrides)
    return argparse.Namespace(**values)


def extract_wrapper(formula_text: str, libexec: str) -> str:
    """Return the bash wrapper the formula writes to bin/, as Ruby would emit it.

    The wrapper lives in a `<<~SH` heredoc. Ruby strips the common indent,
    interpolates `#{libexec}` and processes backslash escapes; this emulates
    the subset the generator relies on.
    """
    match = re.search(r'\.write <<~SH\n(.*?)\n    SH\n', formula_text, re.S)
    if not match:
        raise AssertionError("wrapper heredoc not found in rendered formula")
    body = textwrap.dedent(match.group(1))
    body = body.replace("#{libexec}", libexec)
    body = body.replace('\\"', '"').replace("\\n", "\n")
    return body


class RenderTests(unittest.TestCase):
    def test_class_name_maps_formula_names_to_ruby_classes(self):
        self.assertEqual(gen.class_name("contribute"), "Contribute")
        self.assertEqual(gen.class_name("contribute-candidate"), "ContributeCandidate")
        self.assertEqual(gen.class_name("snake_case_name"), "SnakeCaseName")

    def test_ruby_quote_escapes_backslashes_and_quotes(self):
        self.assertEqual(gen.ruby_quote('plain'), 'plain')
        self.assertEqual(gen.ruby_quote('a"b'), 'a\\"b')
        self.assertEqual(gen.ruby_quote('a\\b'), 'a\\\\b')
        self.assertEqual(gen.ruby_quote('\\"'), '\\\\\\"')

    def test_stable_render_pins_inputs(self):
        args = make_args()
        text = gen.render(args)
        self.assertIn("class Contribute < Formula", text)
        self.assertIn('desc "Hive contribute relay wrapper"\n', text)
        self.assertIn(f'version "{args.version}"', text)
        self.assertIn(f'url "{args.arm64_url}"\n    sha256 "{args.arm64_sha256}"', text)
        self.assertIn(f'url "{args.amd64_url}"\n    sha256 "{args.amd64_sha256}"', text)
        self.assertIn('=> "hive-contributor-stable.sif"', text)
        self.assertIn('(bin/"hive-contribute").write', text)
        self.assertIn(f'IMAGE_REF="{args.image_ref}"', text)
        self.assertIn(f'IMAGE_DIGEST="{args.digest}"', text)
        self.assertIn("tracks the stable channel", text)
        self.assertIn("This file is generated by scripts/generate-formula.py", text)
        self.assertNotIn("pre-release", text)

    def test_candidate_render_is_labelled_and_renamed(self):
        args = make_args(
            formula="contribute-candidate",
            binary="hive-contribute-candidate",
            channel="candidate",
            version="candidate-0123456789ab",
        )
        text = gen.render(args)
        self.assertIn("class ContributeCandidate < Formula", text)
        self.assertIn("(pre-release candidate channel)", text)
        self.assertIn('=> "hive-contributor-candidate.sif"', text)
        self.assertIn('(bin/"hive-contribute-candidate").write', text)
        self.assertIn('CHANNEL="candidate"', text)
        self.assertIn("tracks the candidate pre-release channel", text)
        self.assertIn(
            'assert_match(\n      "hive-contribute-candidate candidate-0123456789ab",',
            text,
        )

    def test_render_substitutes_every_template_placeholder(self):
        # A placeholder added to contribute-wrapper.sh.in without a matching
        # entry in render_wrapper() would ship verbatim inside the formula's
        # heredoc; ruby -c, brew style and brew audit all accept a literal
        # "@FOO@" inside a string, so only this test would notice.
        placeholders = set(re.findall(r"@[A-Z_]+@", gen.WRAPPER_TEMPLATE.read_text(encoding="utf-8")))
        self.assertTrue(placeholders, "template defines no @PLACEHOLDER@ tokens")
        for args in (
            make_args(),
            make_args(formula="contribute-candidate", binary="hive-contribute-candidate",
                      channel="candidate", version="candidate-0123456789ab"),
        ):
            with self.subTest(channel=args.channel):
                text = gen.render(args)
                self.assertEqual(re.findall(r"@[A-Z_]+@", text), [], text)
        committed = SCRIPTS_DIR.parent / "Formula" / "contribute.rb"
        if committed.exists():
            self.assertEqual(re.findall(r"@[A-Z_]+@", committed.read_text(encoding="utf-8")), [])

    def test_render_does_not_force_a_tty_for_docker_run(self):
        text = gen.render(make_args())
        self.assertNotIn("run --rm -it", text)
        self.assertIn("run --rm -i --name", text)

    def test_render_escapes_quotes_in_inputs(self):
        text = gen.render(make_args(version='1"; system("id'))
        self.assertIn('version "1\\"; system(\\"id"', text)
        self.assertNotIn('version "1"; system("id"', text)

    def test_formula_test_block_matches_wrapper_version_output(self):
        args = make_args()
        text = gen.render(args)
        self.assertIn(f'"hive-contribute {args.version}"', text)
        self.assertIn('shell_output("#{bin}/hive-contribute --wrapper-version")', text)

    @unittest.skipUnless(shutil.which("ruby"), "ruby not installed")
    def test_rendered_formula_is_valid_ruby(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "contribute.rb"
            path.write_text(gen.render(make_args()), encoding="utf-8")
            proc = subprocess.run(["ruby", "-c", str(path)], capture_output=True, text=True)
        self.assertEqual(proc.returncode, 0, proc.stderr)

    def test_main_writes_output_file(self):
        args = make_args()
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "Formula" / "contribute.rb"
            out.parent.mkdir()
            cmd = [
                sys.executable, str(GENERATOR),
                "--version", args.version,
                "--digest", args.digest,
                "--image-ref", args.image_ref,
                "--amd64-url", args.amd64_url,
                "--amd64-sha256", args.amd64_sha256,
                "--arm64-url", args.arm64_url,
                "--arm64-sha256", args.arm64_sha256,
                "--output", str(out),
            ]
            proc = subprocess.run(cmd, capture_output=True, text=True)
            self.assertEqual(proc.returncode, 0, proc.stderr)
            self.assertEqual(out.read_text(encoding="utf-8"), gen.render(args))

    def test_main_rejects_unknown_channel(self):
        proc = subprocess.run(
            [sys.executable, str(GENERATOR), "--channel", "nightly", "--version", "v",
             "--digest", "d", "--image-ref", "i", "--amd64-url", "u", "--amd64-sha256", "s",
             "--arm64-url", "u", "--arm64-sha256", "s", "--output", os.devnull],
            capture_output=True, text=True,
        )
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("invalid choice", proc.stderr)


class WrapperTests(unittest.TestCase):
    """Run the generated bash wrapper against stub runtimes."""

    STUB = textwrap.dedent('''\
        #!/usr/bin/env bash
        out="$STUB_OUT"
        : > "$out"
        printf 'ARGV:%s\\n' "$@" >> "$out"
        env | sed 's/^/ENV:/' | sort >> "$out"
        exit "${STUB_EXIT:-0}"
    ''')

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="hive-contribute-test-"))
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.args = make_args()
        self.libexec = self.tmp / "libexec"
        self.libexec.mkdir()
        (self.libexec / "hive-contributor-stable.sif").write_bytes(b"sif")
        self.wrapper = self.tmp / "hive-contribute"
        self.wrapper.write_text(extract_wrapper(gen.render(self.args), str(self.libexec)))
        self.wrapper.chmod(self.wrapper.stat().st_mode | stat.S_IXUSR)
        self.home = self.tmp / "home"
        self.home.mkdir()
        self.bindir = self.tmp / "bin"
        self.bindir.mkdir()
        for tool in HOST_TOOLS + ("sed",):
            src = shutil.which(tool)
            if src:
                os.symlink(src, self.bindir / tool)
        self.stub_out = self.tmp / "stub.out"

    def add_stub(self, name: str) -> None:
        path = self.bindir / name
        path.write_text(self.STUB)
        path.chmod(0o755)

    def run_wrapper(self, *argv, env=None, cwd=None):
        full_env = {
            "PATH": str(self.bindir),
            "HOME": str(self.home),
            "STUB_OUT": str(self.stub_out),
            "HIVE_WORKSPACE_DIR": str(self.tmp / "workspace"),
        }
        if env:
            full_env.update(env)
        return subprocess.run(
            ["bash", str(self.wrapper), *argv],
            env=full_env, cwd=cwd or self.tmp, capture_output=True, text=True,
            stdin=subprocess.DEVNULL,
        )

    def stub_record(self):
        lines = self.stub_out.read_text().splitlines()
        argv = [line[len("ARGV:"):] for line in lines if line.startswith("ARGV:")]
        env = dict(
            line[len("ENV:"):].split("=", 1)
            for line in lines if line.startswith("ENV:") and "=" in line
        )
        return argv, env

    @staticmethod
    def forwarded(argv, env, name):
        """Value a forwarded variable reached the runtime with, via argv or APPTAINERENV_*."""
        for i, arg in enumerate(argv):
            if arg == "--env" and i + 1 < len(argv) and argv[i + 1].startswith(name + "="):
                return argv[i + 1].split("=", 1)[1]
        return env.get("APPTAINERENV_" + name)

    def test_wrapper_is_valid_bash(self):
        proc = subprocess.run(["bash", "-n", str(self.wrapper)], capture_output=True, text=True)
        self.assertEqual(proc.returncode, 0, proc.stderr)

    def test_wrapper_version_matches_formula_test_assertion(self):
        proc = self.run_wrapper("--wrapper-version")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertEqual(
            proc.stdout.strip(),
            f"hive-contribute {self.args.version} channel=stable image={self.args.image_ref}",
        )

    def test_help_flags_print_usage(self):
        for flag in ("--help", "-h"):
            proc = self.run_wrapper(flag)
            self.assertEqual(proc.returncode, 0, flag)
            self.assertIn("Usage: hive-contribute [--wrapper-version]", proc.stdout)
            self.assertIn("HIVE_REGISTRATION_TOKEN", proc.stdout)

    def test_unknown_runtime_is_rejected(self):
        proc = self.run_wrapper(env={"HIVE_CONTRIBUTE_RUNTIME": "firecracker"})
        self.assertEqual(proc.returncode, 2)
        self.assertIn("unknown HIVE_CONTRIBUTE_RUNTIME=firecracker", proc.stderr)

    @unittest.skipUnless(sys.platform.startswith("linux"), "Linux auto-selects apptainer")
    def test_print_runtime_prefers_apptainer_on_linux(self):
        proc = self.run_wrapper("--wrapper-print-runtime")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertEqual(proc.stdout.strip(), "apptainer")

    def test_print_runtime_reports_none_when_nothing_installed(self):
        proc = self.run_wrapper("--wrapper-print-runtime", env={"HIVE_CONTRIBUTE_RUNTIME": "docker"})
        self.assertEqual(proc.returncode, 1)
        self.assertEqual(proc.stdout.strip(), "none")

    def test_print_runtime_finds_requested_engine(self):
        self.add_stub("podman")
        proc = self.run_wrapper("--wrapper-print-runtime", env={"HIVE_CONTRIBUTE_RUNTIME": "podman"})
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertEqual(proc.stdout.strip(), "podman")

    def test_missing_apptainer_fails_with_127(self):
        proc = self.run_wrapper(env={"HIVE_CONTRIBUTE_RUNTIME": "apptainer"})
        self.assertEqual(proc.returncode, 127)
        self.assertIn("apptainer is required on Linux", proc.stderr)

    def test_apptainer_hand_off(self):
        self.add_stub("apptainer")
        (self.home / ".config" / "gh").mkdir(parents=True)
        (self.home / ".gitconfig").write_text("[user]\n")
        proc = self.run_wrapper(
            "relay", "--flag", "value",
            env={
                "HIVE_CONTRIBUTE_RUNTIME": "apptainer",
                "HIVE_REGISTRATION_TOKEN": "reg-token-value",
                "AGENT_BACKEND": "copilot",
                "OPENAI_API_KEY": "openai-value",
                "GH_TOKEN": "gh-token-value",
                "NOT_FORWARDED_SECRET": "must-not-leak",
            },
        )
        self.assertEqual(proc.returncode, 0, proc.stderr)
        argv, env = self.stub_record()

        self.assertEqual(argv[:4], ["run", "--containall", "--writable-tmpfs", "--pwd"])
        self.assertEqual(argv[-4:], [str(self.libexec / "hive-contributor-stable.sif"), "relay", "--flag", "value"])

        self.assertEqual(self.forwarded(argv, env, "HIVE_REGISTRATION_TOKEN"), "reg-token-value")
        self.assertEqual(self.forwarded(argv, env, "AGENT_BACKEND"), "copilot")
        self.assertEqual(self.forwarded(argv, env, "OPENAI_API_KEY"), "openai-value")
        self.assertEqual(self.forwarded(argv, env, "HIVE_CONTAINER_RUNTIME"), "apptainer")
        self.assertEqual(self.forwarded(argv, env, "HIVE_WORKSPACE_DIR"), "/home/dev/workspace")
        self.assertIsNone(self.forwarded(argv, env, "NOT_FORWARDED_SECRET"))
        self.assertNotIn("must-not-leak", " ".join(argv))

        binds = [argv[i + 1] for i, a in enumerate(argv) if a == "--bind"]
        self.assertIn(f"{self.tmp / 'workspace'}:/home/dev/workspace", binds)
        self.assertIn(f"{self.home}/.config/hive:/home/dev/.config/hive", binds)
        self.assertIn(f"{self.home}/.gitconfig:/home/dev/.gitconfig:ro", binds)
        self.assertFalse(any(b.startswith(f"{self.home}/.config/gh:") for b in binds), "gh dir is opt-in")
        self.assertFalse(any(b.startswith(f"{self.home}/.ssh:") for b in binds), "ssh dir is opt-in")
        self.assertEqual(self.forwarded(argv, env, "GIT_CONFIG_COUNT"), "1")
        self.assertEqual(self.forwarded(argv, env, "GIT_CONFIG_KEY_0"), "credential.https://github.com.helper")
        helper = self.forwarded(argv, env, "GIT_CONFIG_VALUE_0")
        self.assertNotIn("gh-token-value", helper, "helper must read the token lazily, not embed it")
        self.assertEqual(
            self.run_credential_helper(helper, {"GH_TOKEN": "gh-token-value"}),
            "username=x-access-token\npassword=gh-token-value\n",
        )

        for created in ("workspace", "home/.config/hive", "home/.local/state/hive/contribute/home",
                        "home/.local/state/hive/contribute/metrics"):
            self.assertTrue((self.tmp / created).is_dir(), created)

    def test_home_workspace_is_refused_by_default(self):
        self.add_stub("apptainer")
        for ws in (str(self.home), str(self.home) + "/", str(self.tmp), "/"):
            proc = self.run_wrapper(
                env={"HIVE_CONTRIBUTE_RUNTIME": "apptainer", "HIVE_WORKSPACE_DIR": ws},
            )
            self.assertEqual(proc.returncode, 2, ws)
            self.assertIn("refusing to use", proc.stderr, ws)
            self.assertFalse(self.stub_out.exists(), f"runtime must not start for {ws}")
        # $PWD is the default workspace, so running from $HOME is the same case.
        proc = self.run_wrapper(env={"HIVE_CONTRIBUTE_RUNTIME": "apptainer", "HIVE_WORKSPACE_DIR": ""}, cwd=self.home)
        self.assertEqual(proc.returncode, 2, proc.stderr)
        self.assertFalse(self.stub_out.exists())

    def test_home_workspace_is_refused_under_unnormalised_spellings(self):
        self.add_stub("apptainer")
        home_link = self.tmp / "home-link"
        home_link.symlink_to(self.home)
        parent_link = self.tmp / "tmp-link"
        parent_link.symlink_to(self.tmp)
        home = str(self.home)
        spellings = (
            f"{home}/.",
            f"{home}//",
            f"{home}/x/..",
            f"{home}/./x/../.",
            "/" + home,
            home.replace("/", "//", 1),
            str(home_link),
            str(home_link) + "/project/..",
            str(parent_link),
            str(parent_link / "home"),
        )
        for ws in spellings:
            proc = self.run_wrapper(
                env={"HIVE_CONTRIBUTE_RUNTIME": "apptainer", "HIVE_WORKSPACE_DIR": ws},
            )
            self.assertEqual(proc.returncode, 2, f"{ws}: {proc.stderr}")
            self.assertIn("refusing to use", proc.stderr, ws)
            self.assertFalse(self.stub_out.exists(), f"runtime must not start for {ws}")
        # Relative spellings resolve against $PWD, so `cd ~ && HIVE_WORKSPACE_DIR=.` is $HOME.
        for ws in (".", "./", "x/..", "./x/../."):
            proc = self.run_wrapper(
                env={"HIVE_CONTRIBUTE_RUNTIME": "apptainer", "HIVE_WORKSPACE_DIR": ws}, cwd=self.home,
            )
            self.assertEqual(proc.returncode, 2, f"{ws}: {proc.stderr}")
            self.assertIn("refusing to use", proc.stderr, ws)
            self.assertFalse(self.stub_out.exists(), f"runtime must not start for {ws}")
        # A symlinked $HOME is still refused when the workspace is spelled via the real path.
        proc = self.run_wrapper(
            env={"HIVE_CONTRIBUTE_RUNTIME": "apptainer", "HIVE_WORKSPACE_DIR": home, "HOME": str(home_link)},
        )
        self.assertEqual(proc.returncode, 2, proc.stderr)
        self.assertFalse(self.stub_out.exists())

    def test_home_workspace_override_and_sibling_dirs_are_allowed(self):
        self.add_stub("apptainer")
        proc = self.run_wrapper(
            env={
                "HIVE_CONTRIBUTE_RUNTIME": "apptainer",
                "HIVE_WORKSPACE_DIR": str(self.home),
                "HIVE_CONTRIBUTE_ALLOW_HOME_WORKSPACE": "1",
            },
        )
        self.assertEqual(proc.returncode, 0, proc.stderr)
        argv, _ = self.stub_record()
        self.assertIn(f"{self.home}:/home/dev/workspace", argv)

        # A directory inside $HOME, one that merely shares a prefix, an
        # unnormalised spelling of a project directory, or a symlink to one is fine.
        (self.home / "project").mkdir()
        project_link = self.tmp / "project-link"
        project_link.symlink_to(self.home / "project")
        for ws in (self.home / "project", Path(str(self.home) + "-other"),
                   self.home / "." / "project", self.home / "x" / ".." / "project", project_link):
            self.stub_out.unlink()
            proc = self.run_wrapper(env={"HIVE_CONTRIBUTE_RUNTIME": "apptainer", "HIVE_WORKSPACE_DIR": str(ws)})
            self.assertEqual(proc.returncode, 0, f"{ws}: {proc.stderr}")
            argv, _ = self.stub_record()
            self.assertIn(f"{ws}:/home/dev/workspace", argv)

    def test_print_runtime_works_from_home(self):
        proc = self.run_wrapper("--wrapper-print-runtime", env={"HIVE_WORKSPACE_DIR": str(self.home)})
        self.assertIn(proc.returncode, (0, 1), proc.stderr)
        self.assertNotIn("refusing to use", proc.stderr)

    def test_apptainer_ssh_and_gh_mounts_are_opt_in(self):
        self.add_stub("apptainer")
        (self.home / ".config" / "gh").mkdir(parents=True)
        (self.home / ".ssh").mkdir()
        proc = self.run_wrapper(env={"HIVE_CONTRIBUTE_RUNTIME": "apptainer"})
        self.assertEqual(proc.returncode, 0, proc.stderr)
        argv, _ = self.stub_record()
        binds = [argv[i + 1] for i, a in enumerate(argv) if a == "--bind"]
        self.assertFalse(any("/.ssh" in b or "/.config/gh" in b for b in binds), binds)

        proc = self.run_wrapper(env={"HIVE_CONTRIBUTE_RUNTIME": "apptainer", "HIVE_CONTRIBUTE_MOUNT_SSH": "1"})
        self.assertEqual(proc.returncode, 0, proc.stderr)
        argv, _ = self.stub_record()
        binds = [argv[i + 1] for i, a in enumerate(argv) if a == "--bind"]
        self.assertIn(f"{self.home}/.ssh:/home/dev/.ssh:ro", binds)
        self.assertFalse(any("/.config/gh" in b for b in binds), binds)

        proc = self.run_wrapper(env={"HIVE_CONTRIBUTE_RUNTIME": "apptainer", "HIVE_CONTRIBUTE_MOUNT_GH": "1"})
        self.assertEqual(proc.returncode, 0, proc.stderr)
        argv, _ = self.stub_record()
        binds = [argv[i + 1] for i, a in enumerate(argv) if a == "--bind"]
        self.assertIn(f"{self.home}/.config/gh:/home/dev/.config/gh", binds)
        self.assertFalse(any("/.ssh" in b for b in binds), binds)

